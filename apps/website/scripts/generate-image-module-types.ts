import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const IMAGE_EXTENSIONS = [
  "avif",
  "bmp",
  "gif",
  "ico",
  "jpeg",
  "jpg",
  "png",
  "svg",
  "webp",
] as const;

const moduleDeclarations = IMAGE_EXTENSIONS.map(
  (extension) => `declare module "*.${extension}" {
  import type { StaticImageData } from "next/image";

  const content: StaticImageData;
  export default content;
}
`,
).join("\n");

const contents = `/* Generated by scripts/generate-image-module-types.ts — do not edit by hand. */

${moduleDeclarations}`;

const outputPath = join(dirname(fileURLToPath(import.meta.url)), "..", "image-modules.d.ts");

writeFileSync(outputPath, contents);
